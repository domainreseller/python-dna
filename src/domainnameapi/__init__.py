"""DomainNameAPI: a Python client for the Domain Name API reseller REST API.

Domain search, registration, renewal and transfer, DNS, DNSSEC, contacts,
SSL certificates, hosting, orders, the product catalogue and your balance.
The operations are grouped the same way as the ``dna`` CLI::

    import domainnameapi as dna

    client = dna.Client(reseller_id, api_key, environment="ote")

    result = client.domains.search("example.com")
    if result.available:
        print(result.domain_name, "is available for", result.price, result.currency)

Every operation is a request class (``DomainInfoRequest``, ``DNSAddRequest``,
...) derived from :class:`BaseRequest`; ``client.send(request)`` sends it, and
your own subclasses too.
"""

